"""Writes firmware/lib/params/scr_param_table.h from params.json (the single source).

python -m scr_serial.gen_params_header            # write the header
python -m scr_serial.gen_params_header --check    # exit 1 if the header is out of date
"""

import argparse
import sys
from pathlib import Path

from scr_serial.params import PARAMS_FILE, load_table

HEADER = Path(__file__).resolve().parents[2] / "firmware" / "lib" / "params" / "scr_param_table.h"


def _num(value: float, kind: str) -> str:
    if kind == "float":
        text = repr(float(value))
        return f"{text}f"
    return f"{int(value)}.0f"


def render() -> str:
    table = load_table(PARAMS_FILE)
    lines = [
        "// GENERATED by scr_serial.gen_params_header from shared/scr_serial/params.json.",
        "// DO NOT EDIT: change params.json and run the generator (a Python test checks it).",
        "// Runtime parameters of the firmware (docs/SERIAL_PROTOCOL.md section 10).",
        "// Defaults are placeholders: an uncalibrated robot does not move. Nothing is measured.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace scr {",
        "namespace params {",
        "",
        f"constexpr uint16_t kTableVersion = {table.version};",
        f"constexpr uint16_t kCount = {len(table.params)};",
        "",
        "enum ParamType : uint8_t { kFloat = 0, kInt = 1, kBool = 2 };",
        "",
        "enum ParamId : uint16_t {",
    ]
    lines += [f"  {p.name} = {p.id}," for p in table.params]
    lines += [
        "};",
        "",
        "struct ParamDef {",
        "  uint16_t id;",
        "  const char* name;",
        "  ParamType type;",
        "  float def;",
        "  float min;",
        "  float max;",
        "};",
        "",
        "// In ascending id order (the order of the parameter hash).",
        "constexpr ParamDef kTable[kCount] = {",
    ]
    kinds = {"float": "kFloat", "int": "kInt", "bool": "kBool"}
    for p in table.params:
        lines.append(
            f'  {{{p.id}, "{p.name}", {kinds[p.type]}, {_num(p.default, p.type)}, '
            f"{_num(p.min, p.type)}, {_num(p.max, p.type)}}},"
        )
    lines += ["};", "", "}  // namespace params", "}  // namespace scr", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--out", type=Path, default=HEADER)
    args = parser.parse_args()
    text = render()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date: run python -m scr_serial.gen_params_header")
            return 1
        print("parameter header up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
